// Evaluator gate for the discovery loop (design §6.1, §6.2) plus the
// population-snapshot helpers of §6.1.
//
// A candidate result is only ever trusted through this gate:
//   1. TRUSTED EXAMPLES first (§6.2 item 1): the positive/negative examples
//      pinned in run-manifest.json `trustedExamples` are supplied BEFORE the
//      loop and are never generated by the evaluator's own generation pass.
//      Their sha256 is re-checked on disk; the evaluator must pass every one.
//   2. PROPERTY DOUBLE-IMPLEMENTATION (§6.2 item 2): an independently
//      generated checker program must agree with the evaluator on every case.
//      Disagreement fails the gate. Two model-generated implementations
//      agreeing is weak evidence — that caveat is documented, not hidden.
//   3. VERSION HASH (§6.2 item 3): the evaluator program's sha256 is pinned
//      into the gate record (and into every claim that cites it); swapping the
//      evaluator mints a new version, which moves affected claims to
//      `revalidation-pending` (§6.3).
// Failing (1) or (2) is a gate failure: exit 1, never a pass with a warning.
//
// Program contract (both the evaluator and the checker): invoked as
//   <program> <case.json>
// and must exit 0 to mean "this case satisfies the claimed property". The
// exit code is the verdict; stdout/stderr tails are preserved as evidence.
// Tests spawn nothing — the subprocess runner is injectable.
//
// Population snapshots (§6.1): population/gen-<n>.json
//   { schemaVersion, rngState, individuals: [{id, program, score,
//     evaluatorVersion, parentIds}] }
// rngState is recorded so a resume can continue the same selection stream;
// `selectParents` is a pure function (top-K by score + K seeded-random), so
// SELECTION is reproducible. Model-generated programs are not bit-reproducible
// (§6.1 honesty note) — never claim otherwise.

export const POPULATION_SCHEMA_VERSION = 1
export const GATE_RECORD_KIND = 'evaluator-gate'
export const DEFAULT_TIMEOUT_MS = 60000
const TAIL = 2000
const HEX64 = /^[a-f0-9]{64}$/
const RNG_MAX = 0xFFFFFFFF

export const populationPath = (runDir, generation) => join(runDir, 'population', `gen-${generation}.json`)

// ---------------------------------------------------------------------------
// Subprocess runner (injectable; SIGTERM then SIGKILL, per-stream tail)
// ---------------------------------------------------------------------------
export function spawnProgram(command, args, { cwd, timeoutMs = DEFAULT_TIMEOUT_MS } = {}) {
  return new Promise(resolveRun => {
    let child
    try { child = nodeSpawn(command, args, { cwd, shell: false, stdio: ['ignore', 'pipe', 'pipe'] }) }
    catch (error) { resolveRun({ exitCode: null, stdout: '', stderr: '', timedOut: false, spawnError: error.message }); return }
    let stdout = ''
    let stderr = ''
    child.stdout.on('data', chunk => { stdout = (stdout + chunk).slice(-TAIL) })
    child.stderr.on('data', chunk => { stderr = (stderr + chunk).slice(-TAIL) })
    let timedOut = false
    const timer = setTimeout(() => {
      timedOut = true
      try { child.kill('SIGTERM') } catch { /* gone */ }
      setTimeout(() => { try { child.kill('SIGKILL') } catch { /* gone */ } }, 2000).unref()
    }, timeoutMs)
    child.once('error', error => { clearTimeout(timer); resolveRun({ exitCode: null, stdout, stderr, timedOut: false, spawnError: error.message }) })
    child.once('close', exitCode => { clearTimeout(timer); resolveRun({ exitCode, stdout, stderr, timedOut }) })
  })
}

const passed = run => run.exitCode === 0 && !run.timedOut && !run.spawnError
const trim = text => (text ?? '').length > TAIL ? `…${text.slice(-TAIL)}` : (text ?? '')

// ---------------------------------------------------------------------------
// Trusted examples (§6.2 item 1)
// ---------------------------------------------------------------------------
async function loadTrustedExamples(runDir, examplesDir, { io = fs } = {}) {
  const manifestPath = join(runDir, 'run-manifest.json')
  if (!(await exists(manifestPath))) fail('config-invalid', `no run-manifest.json in ${resolve(runDir)}`)
  const result = validateRunManifest(await readJson(manifestPath, 'run-manifest.json'))
  if (!result.ok) fail('config-invalid', `run-manifest.json is invalid: ${result.errors.join('; ')}`)
  const declared = result.value.trustedExamples
  if (declared.length === 0) {
    fail('config-invalid', 'run-manifest.json pins no trustedExamples; the evaluator gate cannot run without them (§6.2 item 1)')
  }
  const root = examplesDir === null ? resolve(runDir) : resolve(examplesDir)
  const examples = []
  for (const entry of declared) {
    const path = resolve(root, entry.source)
    assert(await exists(path), `trusted example ${entry.problemId} is missing at ${path}`, 'missing-evidence')
    const actual = await hashFile(path)
    assert(actual === entry.sha256, `trusted example ${entry.problemId} sha256 mismatch: pinned ${entry.sha256}, actual ${actual}`, 'evidence-mismatch')
    examples.push({ problemId: entry.problemId, path, sha256: actual })
  }
  return examples
}

// ---------------------------------------------------------------------------
// Gate
// ---------------------------------------------------------------------------
/**
 * Run one program over a list of case files. `spawnProgram` is injectable so
 * tests never execute a real evaluator.
 */
export async function runProgramOver(program, cases, { run = spawnProgram, cwd = null, timeoutMs = DEFAULT_TIMEOUT_MS } = {}) {
  const results = []
  for (const testCase of cases) {
    const outcome = await run(program, [testCase.path], { cwd: cwd ?? dirname(program), timeoutMs })
    results.push({ case: testCase.problemId ?? testCase.path, path: testCase.path, verdict: passed(outcome) ? 'pass' : 'fail', exitCode: outcome.exitCode ?? null, timedOut: Boolean(outcome.timedOut), stdoutTail: trim(outcome.stdout), stderrTail: trim(outcome.spawnError ? `spawn error: ${outcome.spawnError}\n${outcome.stderr ?? ''}` : outcome.stderr) })
  }
  return results
}

/** §6.2 item 2: the two implementations must agree case by case. */
export function compareImplementations(evaluatorRuns, checkerRuns) {
  const byCase = new Map(checkerRuns.map(entry => [entry.path, entry]))
  const disagreements = []
  for (const evaluatorRun of evaluatorRuns) {
    const checkerRun = byCase.get(evaluatorRun.path)
    if (!checkerRun) { disagreements.push({ case: evaluatorRun.case, reason: 'checker-did-not-run', evaluator: evaluatorRun.verdict, checker: null }); continue }
    if (evaluatorRun.verdict !== checkerRun.verdict) {
      disagreements.push({ case: evaluatorRun.case, reason: 'verdict-disagreement', evaluator: evaluatorRun.verdict, checker: checkerRun.verdict })
    }
  }
  return { cases: evaluatorRuns.length, agreements: evaluatorRuns.length - disagreements.length, disagreements }
}

/**
 * The whole gate. `deps.run` is the injectable subprocess runner; every
 * verdict is recorded with the evaluator/checker version hashes.
 */
export async function evaluateGate({ evaluator, checker, runDir, examplesDir = null }, deps = {}) {
  const { run = spawnProgram, io = fs, now = () => new Date().toISOString(), timeoutMs = DEFAULT_TIMEOUT_MS } = deps
  const evaluatorPath = resolve(evaluator)
  const checkerPath = resolve(checker)
  assert(await exists(evaluatorPath), `evaluator program ${evaluator} does not exist`, 'missing-evidence')
  assert(await exists(checkerPath), `double-implementation checker ${checker} does not exist`, 'missing-evidence')
  const evaluatorVersion = await hashFile(evaluatorPath)
  const checkerVersion = await hashFile(checkerPath)
  assert(evaluatorVersion !== checkerVersion, 'the checker is the same file as the evaluator: that is not an independent implementation (§6.2 item 2)', 'config-invalid')
  const examples = await loadTrustedExamples(runDir, examplesDir, { io })

  const evaluatorRuns = await runProgramOver(evaluatorPath, examples, { run, timeoutMs })
  const trustedFailures = evaluatorRuns.filter(entry => entry.verdict !== 'pass')
  // The double implementation is checked on the same pinned cases: the
  // trusted examples are the only cases the manifest authorises before the
  // loop, so both programs see exactly them.
  const checkerRuns = await runProgramOver(checkerPath, examples, { run, timeoutMs })
  const doubleImplementation = compareImplementations(evaluatorRuns, checkerRuns)

  const decision = trustedFailures.length === 0 && doubleImplementation.disagreements.length === 0 ? 'pass' : 'fail'
  return {
    schemaVersion: 1,
    command: 'evaluator-gate',
    status: decision === 'pass' ? 'passed' : 'failed',
    decision,
    evaluator: { path: evaluatorPath, version: evaluatorVersion },
    checker: { path: checkerPath, version: checkerVersion },
    trustedExamples: evaluatorRuns,
    trustedFailures: trustedFailures.map(entry => entry.case),
    doubleImplementation,
    record: {
      kind: GATE_RECORD_KIND,
      verdict: decision === 'pass' ? 'pass' : 'fail',
      bindingHashes: { evaluator: evaluatorVersion, checker: checkerVersion },
    },
    caveat: 'two model-generated implementations agreeing is weak evidence, not proof (§6.2 item 4)',
    at: now(),
  }
}

// ---------------------------------------------------------------------------
// Population snapshots + seeded selection (§6.1)
// ---------------------------------------------------------------------------
function validateIndividual(individual, index) {
  const label = `individuals[${index}]`
  assert(individual && typeof individual === 'object' && !Array.isArray(individual), `${label} must be an object`)
  const unknown = Object.keys(individual).filter(key => !['id', 'program', 'score', 'evaluatorVersion', 'parentIds'].includes(key))
  assert(unknown.length === 0, `${label} has unknown field(s): ${unknown.join(',')}`)
  assert(typeof individual.id === 'string' && individual.id.trim().length > 0, `${label}.id is required`)
  assert(typeof individual.program === 'string' && individual.program.length > 0, `${label}.program is required`)
  assert(typeof individual.score === 'number' && Number.isFinite(individual.score), `${label}.score must be a finite number`)
  assert(HEX64.test(individual.evaluatorVersion ?? ''), `${label}.evaluatorVersion must be the evaluator's sha256`)
  assert(Array.isArray(individual.parentIds) && individual.parentIds.every(id => typeof id === 'string'), `${label}.parentIds must be an array of individual ids`)
}

export function validatePopulation(population) {
  assert(population && typeof population === 'object' && !Array.isArray(population), 'population snapshot must be an object')
  const unknown = Object.keys(population).filter(key => !['schemaVersion', 'rngState', 'individuals'].includes(key))
  assert(unknown.length === 0, `population snapshot has unknown field(s): ${unknown.join(',')}`)
  assert(population.schemaVersion === POPULATION_SCHEMA_VERSION, `population schemaVersion must be ${POPULATION_SCHEMA_VERSION}`)
  assert(Number.isInteger(population.rngState) && population.rngState >= 0 && population.rngState <= RNG_MAX, `population rngState must be a uint32`)
  assert(Array.isArray(population.individuals), 'population individuals must be an array')
  population.individuals.forEach(validateIndividual)
  const ids = population.individuals.map(individual => individual.id)
  assert(new Set(ids).size === ids.length, 'population individual ids must be unique')
  return population
}

export async function readPopulation(runDir, generation, { io = fs } = {}) {
  return validatePopulation(await readJson(populationPath(runDir, generation), `population/gen-${generation}.json`))
}

export async function writePopulation(runDir, generation, population, { io = fs } = {}) {
  assert(Number.isInteger(generation) && generation >= 0, 'generation must be a non-negative integer')
  validatePopulation(population)
  await io.mkdir(join(runDir, 'population'), { recursive: true })
  await atomicJson(populationPath(runDir, generation), population, io)
  return { subcommand: 'snapshot', generation, path: populationPath(runDir, generation), individuals: population.individuals.length, rngState: population.rngState }
}

/** xorshift32 — a deterministic, dependency-free PRNG for seeded selection. */
export function nextRngState(state) {
  let x = (state >>> 0) || 0x9E3779B9
  x ^= (x << 13) >>> 0
  x >>>= 0
  x ^= x >>> 17
  x ^= (x << 5) >>> 0
  return x >>> 0
}

const drawBelow = (state, bound) => {
  const next = nextRngState(state)
  return { state: next, index: next % bound }
}

/**
 * §6.1 step 1, pure and reproducible: top-K individuals by score (ties broken
 * by id) plus K drawn without replacement from the rest with the seeded PRNG.
 * Returns the selected ids and the advanced rngState, so a resume continues
 * the same stream.
 */
export function selectParents(population, K, rngState) {
  assert(Number.isInteger(K) && K > 0, 'K must be a positive integer')
  const seed = Number.isInteger(rngState) ? rngState : population.rngState
  assert(Number.isInteger(seed) && seed >= 0 && seed <= RNG_MAX, 'rngState must be a uint32')
  const ordered = [...population.individuals].sort((left, right) => right.score - left.score || (left.id < right.id ? -1 : left.id > right.id ? 1 : 0))
  const top = ordered.slice(0, K)
  const rest = ordered.slice(K)
  const parents = top.map(individual => individual.id)
  const pool = [...rest]
  let state = seed
  const draws = Math.min(K, pool.length)
  for (let index = 0; index < draws; index++) {
    const draw = drawBelow(state, pool.length)
    state = draw.state
    const [picked] = pool.splice(draw.index, 1)
    parents.push(picked.id)
  }
  return { parents, top: top.map(individual => individual.id), random: parents.slice(top.length), rngState: state }
}

export async function selectForGeneration(runDir, generation, K, { io = fs } = {}) {
  const population = await readPopulation(runDir, generation, { io })
  assert(K <= population.individuals.length, `K ${K} exceeds the population of ${population.individuals.length} individuals`)
  return { subcommand: 'select', generation, ...selectParents(population, K, population.rngState) }
}

