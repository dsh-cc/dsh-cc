const HELP = [
  'evaluator-gate — discovery-loop evaluator gate and population snapshots (design §6.1, §6.2)',
  'usage: evaluator-gate.mjs <subcommand> [options]',
  '  gate --run <run-dir> --evaluator <program> --checker <program> [--examples <dir>] [--timeout-ms n]',
  '       trusted examples come from run-manifest.json trustedExamples (sha256 re-checked); both programs',
  '       are invoked as "<program> <case.json>" and pass a case by exiting 0',
  '  snapshot --run <run-dir> --generation <n> --individuals <file>   write population/gen-<n>.json',
  '  show --run <run-dir> --generation <n>                            read a snapshot back',
  '  select --run <run-dir> --generation <n> --k <K>                  seeded top-K + K-random parent selection',
  'failing a trusted example or a double-implementation disagreement fails the gate (exit 1)',
  'exit codes: 0 ok/passed · 1 gate failed · 2 blocked (config-invalid, missing-evidence, evidence-mismatch, query-invalid) · single-line JSON on stdout',
].join('\n')

const integer = (value, label) => {
  const parsed = Number(value)
  assert(value !== undefined && Number.isInteger(parsed) && parsed >= 0 && String(parsed) === String(value).trim(), `${label} must be an integer`)
  return parsed
}

async function handle(argv, deps = {}) {
  const options = parseFlags(
    argv,
    ['run', 'evaluator', 'checker', 'examples', 'generation', 'individuals', 'k', 'timeout-ms'],
    { required: ['run'] },
  )
  if (options.help) return 'help'
  if (!options.subcommand) fail('config-invalid', 'a subcommand is required')
  const runDir = resolve(options.run)
  await ensureWritable(runDir)
  switch (options.subcommand) {
    case 'gate': {
      for (const key of ['evaluator', 'checker']) if (!options[key]) fail('config-invalid', `--${key} is required`)
      const timeoutMs = options['timeout-ms'] === undefined ? DEFAULT_TIMEOUT_MS : integer(options['timeout-ms'], '--timeout-ms')
      assert(timeoutMs >= 1000 && timeoutMs <= 600000, '--timeout-ms must be in 1000..600000')
      const report = await evaluateGate({ evaluator: options.evaluator, checker: options.checker, runDir, examplesDir: options.examples ?? null }, { ...deps, timeoutMs })
      return { exitCode: report.decision === 'pass' ? 0 : 1, report }
    }
    case 'snapshot': {
      for (const key of ['generation', 'individuals']) if (!options[key]) fail('config-invalid', `--${key} is required`)
      const generation = integer(options.generation, '--generation')
      const raw = await readJson(resolve(options.individuals), 'individuals file')
      const population = { schemaVersion: POPULATION_SCHEMA_VERSION, rngState: raw.rngState ?? 0, individuals: raw.individuals ?? raw }
      const result = await writePopulation(runDir, generation, population)
      return { exitCode: 0, report: { schemaVersion: 1, command: 'evaluator-gate', status: 'ok', ...result } }
    }
    case 'show': {
      if (options.generation === undefined) fail('config-invalid', '--generation is required')
      const generation = integer(options.generation, '--generation')
      const population = await readPopulation(runDir, generation)
      return { exitCode: 0, report: { schemaVersion: 1, command: 'evaluator-gate', status: 'ok', subcommand: 'show', generation, ...population } }
    }
    case 'select': {
      for (const key of ['generation', 'k']) if (!options[key]) fail('config-invalid', `--${key} is required`)
      const result = await selectForGeneration(runDir, integer(options.generation, '--generation'), integer(options.k, '--k'))
      return { exitCode: 0, report: { schemaVersion: 1, command: 'evaluator-gate', status: 'ok', ...result } }
    }
    default: fail('config-invalid', `unknown subcommand ${options.subcommand}`)
  }
}

export async function main(argv = process.argv.slice(2), deps = {}) {
  return runCli('evaluator-gate', HELP, argv, args => handle(args, deps))
}
if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) process.exitCode = await main()
