const output = (status, reason, summary = null, blockers = []) => ({ schemaVersion: 1, command: 'check', status, reason, blockers, summary })
const blocked = (reason, detail) => output('blocked', reason, null, [{ code: reason, detail }])
export function notRun(c) {
  return { id: c.id, coverage: c.coverage, status: 'not-run', reason: 'not-run', exitCode: null, signal: null, timedOut: null, elapsedMs: null, argv: null, statistics: null, eventCodes: [], stdoutPath: null, stderrPath: null, stdoutSha256: null, stderrSha256: null }
}
export async function generateMissing(paths, manifest, { io = fs, signal, diagnostic = s => process.stderr.write(s + '\n') } = {}) {
  const completed = []
  const cfgs = manifest.cases.map(c => `cases/${c.id}.cfg`)
  for (let i = 0; i < manifest.cases.length; i++) {
    if (signal?.aborted) break
    const c = manifest.cases[i]; const path = join(paths.model, cfgs[i]); const bytes = Buffer.from(generateCfg(c))
    let temp, handle, published = false
    try {
      if (await exists(path)) {
        if (!(await io.readFile(path)).equals(bytes)) fail('config-drift', `${posix(relative(paths.root, path))} differs from generated bytes`)
        completed.push(cfgs[i]); continue
      }
      await io.mkdir(join(paths.model, 'cases'), { recursive: true })
      if (signal?.aborted) break
      temp = temporary(path); handle = await io.open(temp, 'wx'); await handle.writeFile(bytes); await handle.sync(); await handle.close(); handle = null
      if (signal?.aborted) { await io.unlink(temp); temp = null; break }
      try { await io.link(temp, path); published = true }
      catch (e) {
        if (e.code !== 'EEXIST') throw e
        if (!(await io.readFile(path)).equals(bytes)) fail('config-drift', `${posix(relative(paths.root, path))} differs from generated bytes`)
        published = true
      }
      completed.push(cfgs[i]); await io.unlink(temp); temp = null
    } catch (e) {
      if (handle) await handle.close().catch(() => diagnostic('cfg temporary close failed'))
      if (temp) await io.unlink(temp).catch(() => diagnostic('cfg temporary cleanup failed'))
      diagnostic(`cfg completed: ${completed.map(p => posix(relative(paths.root, join(paths.model, p)))).join(', ') || '(none)'}`)
      diagnostic(`cfg unfinished: ${cfgs.slice(published ? i + 1 : i).map(p => posix(relative(paths.root, join(paths.model, p)))).join(', ') || '(none)'}`)
      throw e
    }
  }
}
async function javaLocation(executable) {
  if (isAbsolute(executable)) return executable
  for (const dir of (process.env.PATH ?? '').split(delimiter)) {
    try { const p = join(dir, executable); await fs.access(p, syncFs.constants.X_OK); if ((await fs.stat(p)).isFile()) return await fs.realpath(p) } catch { /* metadata may remain unresolved */ }
  }
  return null
}
export async function executeCheck(options, deps = {}) {
  const { preflight = realPreflight, runCase = realRunCase, io = fs, syncIO = syncFs, signal, hooks = {}, diagnostic = s => process.stderr.write(s + '\n') } = deps
  const cancelled = () => signal?.aborted
  const commandIo = () => cancelled() ? output('incomplete', 'cancelled') : output('error', 'io')
  let paths, lockPath, lockBytes, lockOwned = false, lockIdentity, lockWritten = false, markerStarted = false, committed = false, ctx, evidenceTemp, markerTemp
  const cleanupTemp = async p => { if (p) await io.unlink(p).catch(() => diagnostic('publication temporary cleanup failed')) }
  try {
    if (cancelled()) return output('incomplete', 'cancelled')
    try { paths = await inspectProject(options.project, options.model) }
    catch (e) { return cancelled() ? output('incomplete', 'cancelled') : blocked(['model-path-unsafe', 'config-invalid'].includes(e.code) ? e.code : 'io', e.detail ?? 'project path validation failed') }
    if (cancelled()) return output('incomplete', 'cancelled')
    const startedAt = new Date().toISOString()
    const runId = startedAt.replace(/[-:]/g, '').replace(/\.\d{3}Z$/, 'Z') + '-' + randomUUID()
    lockPath = join(paths.root, '.formal-design/locks', `${paths.modelId}.lock`)
    lockBytes = JSON.stringify({ schemaVersion: 1, pid: process.pid, runId, startedAt }) + '\n'
    try {
      await io.mkdir(join(paths.root, '.formal-design/locks'), { recursive: true })
      if (cancelled()) return output('incomplete', 'cancelled')
      const lock = await io.open(lockPath, 'wx'); lockOwned = true
      try {
        lockIdentity = await lock.stat()
        if (cancelled()) return output('incomplete', 'cancelled')
        await lock.writeFile(lockBytes); await lock.sync(); lockWritten = true
      } finally { await lock.close() }
    } catch (e) {
      if (cancelled()) return output('incomplete', 'cancelled')
      if (e.code === 'EEXIST') { const probe = await probeLock(lockPath); diagnostic(probe.detail ?? 'lock exists'); return blocked('model-locked', 'model lock exists; inspect diagnostics and confirm ownership before manual removal') }
      return blocked('lock-io', 'model lock creation failed')
    }
    if (cancelled()) return output('incomplete', 'cancelled')
    const ready = await preflight(options, { signal })
    if (cancelled() || ready.cancelled) return output('incomplete', 'cancelled')
    if (ready.output.status === 'blocked') return output('blocked', ready.output.reason, null, ready.output.blockers)
    const { manifest, runner, javaVersion, jarSha256 } = ready
    await hooks.afterPreflight?.(ready)
    if (cancelled()) return output('incomplete', 'cancelled')
    await generateMissing(paths, manifest, { io, signal, diagnostic })
    if (cancelled()) return output('incomplete', 'cancelled')
    const captured = await fingerprint(paths.model, manifest)
    if (cancelled()) return output('incomplete', 'cancelled')
    const runDir = join(paths.root, '.formal-design/runs', paths.modelId, runId)
    await io.mkdir(runDir, { recursive: true })
    if (cancelled()) return output('incomplete', 'cancelled')
    const marker = { schemaVersion: 1, runId, inputDigest: captured.inputDigest, state: 'running' }
    const markerPath = join(paths.model, 'current-run.json')
    await atomicJson(markerPath, marker, io); markerStarted = true
    const snapshot = join(runDir, 'input')
    ctx = { paths, manifest, runner, options, runDir, snapshot, marker, markerPath, startedAt, jarSha256, javaVersion, ...captured, cases: manifest.cases.map(notRun), globals: [] }
    let cannotPersist = false
    try {
      if (!cancelled()) {
        await io.mkdir(join(snapshot, 'cases'), { recursive: true })
        for (const f of captured.inputFiles) {
          if (cancelled()) break
          await io.copyFile(join(paths.model, f.path), join(snapshot, f.path))
        }
        if (!cancelled()) {
          await hooks.afterSnapshot?.(ctx)
          if ((await fingerprint(snapshot, manifest)).inputDigest !== captured.inputDigest) ctx.globals.push('input-changed')
        }
      }
      for (let i = 0; i < manifest.cases.length; i++) {
        if (cancelled() || ctx.globals.length) break
        const c = manifest.cases[i]
        await hooks.beforeCase?.(ctx, i)
        if (cancelled()) break
        const dir = join(runDir, c.id)
        const argv = [options.java, `-Xmx${c.limits.heapMiB}m`, '-cp', options.jar, 'tlc2.TLC', '-tool', '-workers', '1', '-seed', '1', '-fp', '0', '-metadir', join(dir, 'states'), '-config', join(snapshot, `cases/${c.id}.cfg`), manifest.module]
        try {
          const result = await runCase(c, argv, snapshot, dir, { signal, io })
          for (const key of ['stdoutPath', 'stderrPath']) result[key] = posix(relative(paths.root, result[key]))
          ctx.cases[i] = result
        } catch (e) { if (e.lostOutput) cannotPersist = true; throw e }
        await hooks.afterCase?.(ctx, i)
      }
    } catch (e) { ctx.globals.push('io'); diagnostic('run preparation or log persistence failed'); if (e.lostOutput) cannotPersist = true }
    // Missing/unreadable captured inputs/artifacts are changes, not old success.
    try { if ((await fingerprint(paths.model, manifest)).inputDigest !== captured.inputDigest) ctx.globals.push('input-changed') } catch { ctx.globals.push('input-changed') }
    try {
      const current = await runnerIdentity()
      if (current.runnerDigest !== runner.runnerDigest || JSON.stringify(current.runnerPackage) !== JSON.stringify(runner.runnerPackage) || current.toolchainDigest !== runner.toolchainDigest || await hashFile(options.jar) !== jarSha256) ctx.globals.push('artifact-changed')
    } catch { ctx.globals.push('artifact-changed') }
    if (cannotPersist) return commandIo()
    await hooks.beforePublication?.(ctx)
    const build = async () => {
      const globals = [...ctx.globals, ...(cancelled() ? ['cancelled'] : [])]
      return { schemaVersion: 1, runId, modelId: manifest.modelId, ...captured, runnerDigest: runner.runnerDigest, runnerPackage: runner.runnerPackage, toolchainVersion: runner.toolchainVersion, toolchainDigest: runner.toolchainDigest, jarSha256, jarPath: options.jar, javaVersion, javaExecutable: await javaLocation(options.java), platform: process.platform, startedAt, finishedAt: new Date(Math.max(Date.now(), Date.parse(startedAt))).toISOString(), ...aggregate(ctx.cases, globals), cases: ctx.cases.map(({ warningCodes, ...rest }) => rest) }
    }
    let evidence, cancellationAtStage
    // One recovery attempt is allowed for Evidence staging, never for a failed
    // final marker. No asynchronous work occurs in the final publication pair.
    for (let attempt = 0; attempt < 2; attempt++) {
      try {
        do {
          await cleanupTemp(evidenceTemp); evidenceTemp = null
          await cleanupTemp(markerTemp); markerTemp = null
          cancellationAtStage = cancelled(); evidence = await build()
          evidenceTemp = await stageJson(join(paths.model, 'evidence.json'), evidence, io)
          markerTemp = await stageJson(markerPath, { ...marker, state: 'finished' }, io)
          await atomicJson(join(runDir, 'evidence.json'), evidence, io)
          await hooks.afterStaging?.(ctx)
        } while (cancellationAtStage !== cancelled())
        break
      } catch {
        ctx.globals.push('io'); diagnostic('Evidence staging failed')
        if (attempt) return commandIo()
      }
    }
    // Synchronous handler-observation boundary (§10.1). Test hook is synchronous.
    try {
      syncIO.renameSync(evidenceTemp, join(paths.model, 'evidence.json')); evidenceTemp = null
    } catch { return commandIo() }
    try {
      hooks.beforeFinishedMarker?.(ctx)
      syncIO.renameSync(markerTemp, markerPath); markerTemp = null
      committed = true
    } catch { diagnostic('finished marker publication failed; run remains incomplete'); return commandIo() }
    const result = output(evidence.status, evidence.reason, evidence)
    try { await hooks.afterPublication?.(ctx) } catch { diagnostic('post-publication cleanup hook failed') }
    return result
  } catch (e) {
    diagnostic(e.detail ?? 'check filesystem operation failed')
    if (committed) throw e
    if (markerStarted) return commandIo()
    if (cancelled()) return output('incomplete', 'cancelled')
    return blocked(e.code === 'config-drift' ? 'config-drift' : 'io', e.detail ?? 'pre-run preparation failed')
  } finally {
    await cleanupTemp(evidenceTemp); await cleanupTemp(markerTemp)
    if (lockOwned) {
      try {
        // Exclusive creation proves ownership even if the initial write failed;
        // a replacement is never removed based on its PID alone.
        const stat = await io.lstat(lockPath)
        const current = await io.readFile(lockPath, 'utf8')
        if (lockIdentity && stat.dev === lockIdentity.dev && stat.ino === lockIdentity.ino && (!lockWritten || current === lockBytes)) await io.unlink(lockPath)
        else diagnostic('lock contents changed; owned-lock cleanup refused')
      } catch { diagnostic('owned-lock cleanup failed; inspect recorded ownership before removal') }
    }
  }
}
